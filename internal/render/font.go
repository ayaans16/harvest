// rows splits a '/'-joined bitmap into rows.
func rows(s string) []string { return strings.Split(s, "/") }

func glyph(r rune) []string {
	if r >= 'a' && r <= 'z' {
		r -= 32
	}
	g, ok := glyphs[r]
	if !ok {
		g = glyphs['?']
	}
	return rows(g)
}

// textWidth returns the pixel width of s at the given scale.
func textWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return n*4*scale - scale
}
